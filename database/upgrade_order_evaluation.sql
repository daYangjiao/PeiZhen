-- 升级脚本：新增订单评价表
CREATE TABLE IF NOT EXISTS `order_evaluation` (
  `id` INT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
  `order_id` INT NOT NULL COMMENT '订单ID',
  `order_no` VARCHAR(64) NOT NULL COMMENT '订单号',
  `user_id` INT NOT NULL COMMENT '评价用户ID',
  `attendant_id` INT NULL DEFAULT NULL COMMENT '陪诊师用户ID',
  `rating` INT NOT NULL COMMENT '总体评分（1-5星）',
  `tags` VARCHAR(255) NULL DEFAULT NULL COMMENT '服务亮点标签，逗号分隔',
  `content` TEXT NULL COMMENT '评价内容',
  `create_time` DATETIME NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`) USING BTREE,
  UNIQUE KEY `uk_order_id` (`order_id`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='订单评价表';

